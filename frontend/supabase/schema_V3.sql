-- 4. TABLA EJERCICIO (Ajustada para RF-08, RF-09 y RF-15)
CREATE TABLE public.ejercicio (
    id_ejercicio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_creador UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    url_video TEXT NOT NULL,
    dificultad VARCHAR(50),
    categoria VARCHAR(100),
    zona_cuerpo VARCHAR(100),
    objetivo TEXT,
    instrucciones TEXT,
    duracion_segundos INTEGER NOT NULL CHECK (duracion_segundos > 0),
    segundo_inicio INTEGER DEFAULT 0 CHECK (segundo_inicio >= 0),
    segundo_termino INTEGER CHECK (segundo_termino IS NULL OR segundo_termino > segundo_inicio),
    estado VARCHAR(50) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'retirado')),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. TABLA RUTINA (Ajustada para RF-05, RF-05b y RF-06)
CREATE TABLE public.rutina (
    id_rutina INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_creador UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE RESTRICT,
    id_curso INTEGER REFERENCES public.curso(id_curso) ON DELETE SET NULL,
    copia_de INTEGER REFERENCES public.rutina(id_rutina) ON DELETE SET NULL,
    credito_autor_original VARCHAR(200),
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    intensidad VARCHAR(50),
    visibilidad VARCHAR(50) NOT NULL DEFAULT 'privada' CHECK (visibilidad IN ('privada', 'publica')),
    estado VARCHAR(50) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'retirada')),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. TABLA RUTINA_PARTES (Reemplaza a asignacion_rutina según RF-07)
CREATE TABLE public.rutina_partes (
    id_rutina_parte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rutina INTEGER NOT NULL REFERENCES public.rutina(id_rutina) ON DELETE CASCADE,
    tipo VARCHAR(50) NOT NULL CHECK (tipo IN ('sesion', 'bloque', 'dia')),
    nombre VARCHAR(150) NOT NULL,
    orden INTEGER NOT NULL
);

-- 7. TABLA RUTINA_EJERCICIO (Conectada a rutina_partes; duración e instrucciones van en ejercicio)
CREATE TABLE public.rutina_ejercicio (
    id_rutina_ejercicio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rutina INTEGER NOT NULL REFERENCES public.rutina(id_rutina) ON DELETE CASCADE,
    id_rutina_parte INTEGER REFERENCES public.rutina_partes(id_rutina_parte) ON DELETE CASCADE,
    id_ejercicio INTEGER NOT NULL REFERENCES public.ejercicio(id_ejercicio) ON DELETE RESTRICT,
    orden INTEGER NOT NULL
);

-- 8. TABLA RUTINA_COMPARTIDA (RF-06c)
CREATE TABLE public.rutina_compartida (
    id_compartida INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rutina INTEGER NOT NULL REFERENCES public.rutina(id_rutina) ON DELETE CASCADE,
    id_usuario_destinatario UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
    id_usuario_compartidor UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
    permiso_edicion BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_compartida TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(50) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'revocada')),
    UNIQUE (id_rutina, id_usuario_destinatario)
);

-- 9. TABLA REGISTRO_PAUSA (Ajustada para RF-12: sin id_asignacion, con parte y terminada)
CREATE TABLE public.registro_pausa (
    id_registro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
    id_rutina INTEGER NOT NULL REFERENCES public.rutina(id_rutina) ON DELETE CASCADE,
    id_rutina_parte INTEGER REFERENCES public.rutina_partes(id_rutina_parte) ON DELETE SET NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_fin TIMESTAMPTZ,
    duracion_segundos INTEGER,
    terminada BOOLEAN NOT NULL DEFAULT FALSE
);

-- 10. TABLA REPORTE (Ajustada para RF-16 con decision_admin)
CREATE TABLE public.reporte (
    id_reporte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_reporta UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
    id_rutina INTEGER REFERENCES public.rutina(id_rutina) ON DELETE SET NULL,
    id_ejercicio INTEGER REFERENCES public.ejercicio(id_ejercicio) ON DELETE SET NULL,
    motivo VARCHAR(150) NOT NULL,
    descripcion TEXT,
    estado VARCHAR(50) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'resuelto')),
    decision_admin VARCHAR(50) CHECK (decision_admin IN ('retirar', 'hacer_privada', 'descartar')),
    fecha_reporte TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_resolucion TIMESTAMPTZ,
    CONSTRAINT chk_objetivo_reporte CHECK (id_rutina IS NOT NULL OR id_ejercicio IS NOT NULL)
);

-- 11. TABLA NUEVA: ACEPTACION_TERMINOS (RF-15)
CREATE TABLE public.aceptacion_terminos (
    id_aceptacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario UUID NOT NULL REFERENCES public.perfiles(id) ON DELETE CASCADE,
    version_terminos VARCHAR(50) NOT NULL,
    fecha_aceptacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id_usuario, version_terminos)
);

-- ============================================================================
-- FUNCIONES AUXILIARES DE SEGURIDAD (Evitan recursión infinita en políticas RLS)
-- ============================================================================

CREATE OR REPLACE FUNCTION public.es_admin()
RETURNS BOOLEAN AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.perfiles
    WHERE id = auth.uid() AND rol = 'admin' AND activo = TRUE
  );
$$ LANGUAGE sql SECURITY DEFINER STABLE;

CREATE OR REPLACE FUNCTION public.mi_colegio_id()
RETURNS INTEGER AS $$
  SELECT id_colegio FROM public.perfiles
  WHERE id = auth.uid() AND activo = TRUE;
$$ LANGUAGE sql SECURITY DEFINER STABLE;

CREATE OR REPLACE FUNCTION public.puede_crear()
RETURNS BOOLEAN AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.perfiles
    WHERE id = auth.uid() AND activo = TRUE AND (rol = 'admin' OR puede_crear_contenido = TRUE)
  );
$$ LANGUAGE sql SECURITY DEFINER STABLE;

