-- 1. TABLA COLEGIO
-- Se elimina id_usuario_perfil; la relación vive en perfiles.id_colegio
CREATE TABLE public.colegio (
    id_colegio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    direccion VARCHAR(255),
    telefono VARCHAR(50),
    correo VARCHAR(150),
    estado VARCHAR(50) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. TABLA PERFILES (Reemplaza a usuario y rol, ligada a Supabase Auth)
CREATE TABLE public.perfiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    id_colegio INTEGER REFERENCES public.colegio(id_colegio) ON DELETE SET NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'docente' CHECK (rol IN ('admin', 'colegio', 'docente')),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    correo VARCHAR(150) UNIQUE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    puede_crear_contenido BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. TABLA CURSO (Lista fija de 1° a 4° básico, sin id_colegio)
CREATE TABLE public.curso (
    id_curso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    nivel VARCHAR(100),
    descripcion TEXT
);

