-- ============================================================================
-- POLÍTICAS RLS BASE (Cada integrante refinará las específicas de su módulo)
-- ============================================================================

-- COLEGIO: Autenticados leen colegios activos; solo admin crea/edita
CREATE POLICY "Lectura de colegios para autenticados" ON public.colegio
    FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin gestiona colegios" ON public.colegio
    FOR ALL TO authenticated USING (public.es_admin()) WITH CHECK (public.es_admin());

-- PERFILES:
-- Cada uno ve su perfil; cuenta 'colegio' ve los de su colegio; 'admin' ve todos
CREATE POLICY "Ver perfiles segun rol" ON public.perfiles
    FOR SELECT TO authenticated USING (
        id = auth.uid()
        OR public.es_admin()
        OR (
            EXISTS (SELECT 1 FROM public.perfiles p WHERE p.id = auth.uid() AND p.rol = 'colegio')
            AND id_colegio = public.mi_colegio_id()
        )
    );
CREATE POLICY "Admin gestiona perfiles" ON public.perfiles
    FOR ALL TO authenticated USING (public.es_admin()) WITH CHECK (public.es_admin());

-- CURSO: Lectura pública para autenticados; solo admin modifica
CREATE POLICY "Lectura de cursos" ON public.curso
    FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin gestiona cursos" ON public.curso
    FOR ALL TO authenticated USING (public.es_admin()) WITH CHECK (public.es_admin());

-- EJERCICIO:
-- Todos ven los activos (el dueño y admin ven también retirados)
CREATE POLICY "Ver ejercicios activos o propios" ON public.ejercicio
    FOR SELECT TO authenticated USING (
        estado = 'activo' OR id_usuario_creador = auth.uid() OR public.es_admin()
    );
-- Solo crea quien tiene el permiso puede_crear_contenido (o admin)
CREATE POLICY "Crear ejercicios con permiso" ON public.ejercicio
    FOR INSERT TO authenticated WITH CHECK (
        id_usuario_creador = auth.uid() AND public.puede_crear()
    );
CREATE POLICY "Editar ejercicios propios o admin" ON public.ejercicio
    FOR UPDATE TO authenticated USING (
        id_usuario_creador = auth.uid() OR public.es_admin()
    );

-- RUTINA (Base para RF-05, RF-06 y RF-06c):
CREATE POLICY "Ver rutinas publicas, propias o compartidas" ON public.rutina
    FOR SELECT TO authenticated USING (
        (visibilidad = 'publica' AND estado = 'activa')
        OR id_usuario_creador = auth.uid()
        OR public.es_admin()
        OR EXISTS (
            SELECT 1 FROM public.rutina_compartida rc
            WHERE rc.id_rutina = rutina.id_rutina
              AND rc.id_usuario_destinatario = auth.uid()
              AND rc.estado = 'activa'
        )
    );
CREATE POLICY "Crear rutinas con permiso" ON public.rutina
    FOR INSERT TO authenticated WITH CHECK (
        id_usuario_creador = auth.uid() AND public.puede_crear()
    );
CREATE POLICY "Editar rutinas propias o admin" ON public.rutina
    FOR UPDATE TO authenticated USING (
        id_usuario_creador = auth.uid() OR public.es_admin()
    );
CREATE POLICY "Eliminar rutinas propias o admin" ON public.rutina
    FOR DELETE TO authenticated USING (
        id_usuario_creador = auth.uid() OR public.es_admin()
    );

-- RUTINA_PARTES y RUTINA_EJERCICIO: Heredan visibilidad/edición de la rutina padre
CREATE POLICY "Ver partes de rutinas accesibles" ON public.rutina_partes
    FOR SELECT TO authenticated USING (
        EXISTS (SELECT 1 FROM public.rutina r WHERE r.id_rutina = rutina_partes.id_rutina)
    );
CREATE POLICY "Gestionar partes de rutina propia" ON public.rutina_partes
    FOR ALL TO authenticated USING (
        EXISTS (
            SELECT 1 FROM public.rutina r
            WHERE r.id_rutina = rutina_partes.id_rutina
              AND (r.id_usuario_creador = auth.uid() OR public.es_admin())
        )
    );

CREATE POLICY "Ver ejercicios de rutinas accesibles" ON public.rutina_ejercicio
    FOR SELECT TO authenticated USING (
        EXISTS (SELECT 1 FROM public.rutina r WHERE r.id_rutina = rutina_ejercicio.id_rutina)
    );
CREATE POLICY "Gestionar ejercicios de rutina propia" ON public.rutina_ejercicio
    FOR ALL TO authenticated USING (
        EXISTS (
            SELECT 1 FROM public.rutina r
            WHERE r.id_rutina = rutina_ejercicio.id_rutina
              AND (r.id_usuario_creador = auth.uid() OR public.es_admin())
        )
    );

-- RUTINA_COMPARTIDA:
CREATE POLICY "Ver rutinas compartidas involucradas" ON public.rutina_compartida
    FOR SELECT TO authenticated USING (
        id_usuario_destinatario = auth.uid()
        OR id_usuario_compartidor = auth.uid()
        OR public.es_admin()
    );
CREATE POLICY "Compartir rutinas propias" ON public.rutina_compartida
    FOR INSERT TO authenticated WITH CHECK (
        id_usuario_compartidor = auth.uid()
        AND EXISTS (
            SELECT 1 FROM public.rutina r
            WHERE r.id_rutina = rutina_compartida.id_rutina AND r.id_usuario_creador = auth.uid()
        )
    );
CREATE POLICY "Revocar compartidos propios" ON public.rutina_compartida
    FOR DELETE TO authenticated USING (
        id_usuario_compartidor = auth.uid() OR public.es_admin()
    );

-- REGISTRO_PAUSA (Docente ve los suyos, Colegio ve los de sus docentes, Admin ve todos):
CREATE POLICY "Insertar propios registros de pausa" ON public.registro_pausa
    FOR INSERT TO authenticated WITH CHECK (id_usuario = auth.uid());
CREATE POLICY "Actualizar propios registros de pausa" ON public.registro_pausa
    FOR UPDATE TO authenticated USING (id_usuario = auth.uid());
CREATE POLICY "Ver registros de pausa segun rol" ON public.registro_pausa
    FOR SELECT TO authenticated USING (
        id_usuario = auth.uid()
        OR public.es_admin()
        OR EXISTS (
            SELECT 1 FROM public.perfiles docente
            WHERE docente.id = registro_pausa.id_usuario
              AND docente.id_colegio = public.mi_colegio_id()
              AND EXISTS (SELECT 1 FROM public.perfiles yo WHERE yo.id = auth.uid() AND yo.rol = 'colegio')
        )
    );

-- REPORTE:
CREATE POLICY "Crear reportes" ON public.reporte
    FOR INSERT TO authenticated WITH CHECK (id_usuario_reporta = auth.uid());
CREATE POLICY "Ver reportes propios o admin" ON public.reporte
    FOR SELECT TO authenticated USING (id_usuario_reporta = auth.uid() OR public.es_admin());
CREATE POLICY "Admin resuelve reportes" ON public.reporte
    FOR UPDATE TO authenticated USING (public.es_admin());

-- ACEPTACION_TERMINOS:
CREATE POLICY "Ver y registrar propia aceptacion de terminos" ON public.aceptacion_terminos
    FOR SELECT TO authenticated USING (id_usuario = auth.uid() OR public.es_admin());
CREATE POLICY "Insertar aceptacion de terminos" ON public.aceptacion_terminos
    FOR INSERT TO authenticated WITH CHECK (id_usuario = auth.uid());